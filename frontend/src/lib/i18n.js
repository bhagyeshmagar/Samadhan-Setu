const CATEGORY_KEY_MAP = {
    all: 'cat_all',
    'roads & transport': 'cat_roads',
    'water supply': 'cat_water',
    electricity: 'cat_electricity',
    'sanitation & waste': 'cat_sanitation',
    'health & safety': 'cat_health',
    general: 'cat_general',
};

const LanguageContext = createContext({
    lang: 'en',
    locale: 'en-IN',
    setLang: () => {},
    t: (key) => key,
    tStatus: (s) => s,
    tPriority: (p) => p,
    tRole: (r) => r,
    tCategory: (c) => c,
    tEvent: (e) => e,
    tEventDesc: (e) => e,
    languages: LANGUAGES,
});

function interpolate(template, params) {
    if (!params || typeof template !== 'string') return template;
    return template.replace(/\{(\w+)\}/g, (_, key) =>
        params[key] !== undefined && params[key] !== null ? String(params[key]) : `{${key}}`
    );
}

export function LanguageProvider({ children }) {
    const [lang, setLangState] = useState('en');

    // Hydration-safe read from localStorage after mount
    useEffect(() => {
        const timer = setTimeout(() => {
            try {
                const stored = localStorage.getItem('samadhan_lang');
                if (stored && LANGUAGES[stored]) {
                    setLangState(stored);
                }
            } catch {
                // Ignore storage errors
            }
        }, 0);
        return () => clearTimeout(timer);
    }, []);

    // Keep <html lang="..."> synced for Devanagari fonts & accessibility
    useEffect(() => {
        if (typeof document !== 'undefined') {
            document.documentElement.lang = lang;
        }
    }, [lang]);

    const setLang = useCallback((newLang) => {
        if (LANGUAGES[newLang]) {
            setLangState(newLang);
            try {
                localStorage.setItem('samadhan_lang', newLang);
            } catch {
                // Ignore storage errors
            }
        }
    }, []);

    const t = useCallback(
        (key, params) => {
            const raw = DICTIONARY[lang]?.[key] ?? DICTIONARY.en?.[key] ?? key;
            return interpolate(raw, params);
        },
        [lang]
    );

    const tStatus = useCallback(
        (status) => {
            if (!status) return t('status_pending');
            const norm = String(status).toLowerCase().trim().replace(/\s+/g, '_');
            const dictKey = `status_${norm}`;
            if (DICTIONARY[lang]?.[dictKey]) return DICTIONARY[lang][dictKey];
            if (DICTIONARY.en?.[dictKey]) return DICTIONARY.en[dictKey];
            return norm
                .replace(/_/g, ' ')
                .split(' ')
                .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
                .join(' ');
        },
        [lang, t]
    );

    const tPriority = useCallback(
        (priority) => {
            if (!priority) return t('priority_medium');
            const norm = String(priority).toLowerCase().trim();
            const dictKey = `priority_${norm}`;
            return DICTIONARY[lang]?.[dictKey] ?? DICTIONARY.en?.[dictKey] ?? priority;
        },
        [lang, t]
    );

    const tRole = useCallback(
        (role) => {
            if (!role) return t('role_citizen');
            const norm = String(role).toLowerCase().trim();
            const dictKey = `role_${norm}`;
            return DICTIONARY[lang]?.[dictKey] ?? DICTIONARY.en?.[dictKey] ?? role;
        },
        [lang, t]
    );

    const tCategory = useCallback(
        (category) => {
            if (!category) return t('cat_general');
            const norm = String(category).toLowerCase().trim();
            const dictKey = CATEGORY_KEY_MAP[norm];
            if (dictKey) return DICTIONARY[lang]?.[dictKey] ?? DICTIONARY.en?.[dictKey] ?? category;
            return category;
        },
        [lang, t]
    );

    const tEvent = useCallback(
        (eventKey) => {
            const dictKey = `evt_${eventKey}`;
            return DICTIONARY[lang]?.[dictKey] ?? DICTIONARY.en?.[dictKey] ?? eventKey;
        },
        [lang]
    );

    const tEventDesc = useCallback(
        (eventKey) => {
            const dictKey = `evt_${eventKey}_desc`;
            return DICTIONARY[lang]?.[dictKey] ?? DICTIONARY.en?.[dictKey] ?? '';
        },
        [lang]
    );

    const locale = LANGUAGES[lang]?.locale || 'en-IN';

    return (
        <LanguageContext.Provider
            value={{
                lang,
                locale,
                setLang,
                t,
                tStatus,
                tPriority,
                tRole,
                tCategory,
                tEvent,
                tEventDesc,
                languages: LANGUAGES,
            }}
        >
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    return useContext(LanguageContext);
}
